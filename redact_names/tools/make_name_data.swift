// Builds Sources/redact_names/NameData.swift: the name list that is compiled into the tool.
//
// Inputs (public data, nothing about students):
//   baby-names.csv   https://raw.githubusercontent.com/hadley/data-baby-names/master/baby-names.csv
//   surnames.csv     https://raw.githubusercontent.com/fivethirtyeight/data/master/most-common-name/surnames.csv
//   /usr/share/dict/propernames, /usr/share/dict/connectives  (ship with macOS)
//
// Run:  swift tools/make_name_data.swift baby-names.csv surnames.csv
import Foundation

let args = CommandLine.arguments
guard args.count == 3 else { print("usage: make_name_data.swift baby-names.csv surnames.csv"); exit(1) }

func lines(_ path: String) -> [String] {
    (try? String(contentsOfFile: path, encoding: .utf8))?.split(whereSeparator: \.isNewline).map(String.init) ?? []
}
func clean(_ s: String) -> String {
    s.trimmingCharacters(in: CharacterSet(charactersIn: "\" "))
        .folding(options: [.diacriticInsensitive, .caseInsensitive], locale: nil)
}

var names = Set<String>()
// First names: columns are year,"name",percent,"sex"
for l in lines(args[1]).dropFirst() { names.insert(clean(l.split(separator: ",")[1].description)) }
names.formUnion(lines("/usr/share/dict/propernames").map(clean))
// Surnames: name,rank,... take the 25,000 most common
for l in lines(args[2]).dropFirst().prefix(25_000) { names.insert(clean(l.split(separator: ",")[0].description)) }

// Drop function words ("the", "and", ...): they appear in the surname data but are never useful hits.
let connectives = Set(lines("/usr/share/dict/connectives").map(clean))
let kept = names.filter { $0.count >= 3 && $0.allSatisfy { $0.isLetter } && !connectives.contains($0) }.sorted()
var out = "// GENERATED by tools/make_name_data.swift. Do not edit by hand.\n"
out += "// \(kept.count) lowercase names (first names and common surnames).\n\n"
out += "enum NameData {\n    static let all: [Substring] = raw.split(whereSeparator: \\.isWhitespace)\n\n    private static let raw = \"\"\"\n"
var row: [String] = []
for n in kept { row.append(n); if row.count == 12 { out += row.joined(separator: " ") + "\n"; row = [] } }
if !row.isEmpty { out += row.joined(separator: " ") + "\n" }
out += "\"\"\"\n}\n"
try out.write(toFile: "Sources/redact_names/NameData.swift", atomically: true, encoding: .utf8)
print("wrote \(kept.count) names")
